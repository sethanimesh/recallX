import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative, join } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

export async function buildWebOffline(directory) {
  const files = [];
  async function walk(path) { for (const entry of await readdir(path, { withFileTypes: true })) { const full = join(path, entry.name); if (entry.isDirectory()) await walk(full); else if (!['sw.js', 'offline-manifest.json'].includes(entry.name)) files.push(full); } }
  await walk(directory); files.sort();
  const hash = createHash('sha256');
  const assets = [];
  for (const file of files) { const path = `/${relative(directory, file).split('\\').join('/')}`; hash.update(path); hash.update(await readFile(file)); assets.push(path); }
  const version = hash.digest('hex').slice(0, 20);
  const routes = assets.filter(path => path.endsWith('.html')).map(path => path.slice(0, -5));
  const manifest = { version, assets, routes };
  const source = `// Generated by build-web-offline.mjs. Never cache API responses or authenticated requests.
const MANIFEST = ${JSON.stringify(manifest)};
const CACHE = 'recallx-shell-' + MANIFEST.version;
const ASSETS = new Set(MANIFEST.assets);
const ROUTES = new Set(MANIFEST.routes.concat(['/']));
self.addEventListener('install', event => event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(MANIFEST.assets))));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const name of await caches.keys()) if (name.startsWith('recallx-shell-') && name !== CACHE) await caches.delete(name);
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const request = event.request; const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || request.headers.has('Authorization')) return;
  const path = decodeURIComponent(url.pathname);
  const route = path === '/' ? '/index' : path.replace(/\\/$/, '');
  const isNavigation = request.mode === 'navigate' && (ROUTES.has(route) || /^\\/words\\/[^/]+$/.test(route));
  if (!isNavigation && !ASSETS.has(path)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (isNavigation) {
      try { const response = await fetch(request); if (response.ok) return response; } catch {}
      return (await cache.match(route + '.html')) || (await cache.match('/index.html')) || Response.error();
    }
    return (await cache.match(path)) || fetch(request);
  })());
});
`;
  await writeFile(join(directory, 'sw.js'), source);
  await writeFile(join(directory, 'offline-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = await buildWebOffline(resolve(process.argv[2] ?? 'dist'));
  console.log(`Offline shell ${manifest.version}: ${manifest.assets.length} static files; API responses excluded.`);
}
